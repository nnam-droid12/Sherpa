import { CATEGORY_LABELS, type Audit, type Run } from "./types";

const esc = (s: unknown) =>
  String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

function auditSection(title: string, a: Audit) {
  const cats = Object.entries(a.categories)
    .map(([k, c]) => `<tr><td>${esc(CATEGORY_LABELS[k] ?? k)}</td><td>${c.score}/${c.max}</td></tr>`)
    .join("");
  const findings = a.findings
    .map(
      (f) => `<li><strong>[${esc(f.severity)}] ${esc(f.title)}</strong><br>
      <em>Impact:</em> ${esc(f.impact)}<br><em>Fix:</em> ${esc(f.fix)}</li>`,
    )
    .join("");
  return `<h2>${esc(title)}: ${a.total}/100</h2><table>${cats}</table><h3>Findings</h3><ol>${findings || "<li>None</li>"}</ol>`;
}

/** Self-contained HTML report a merchant can save or print to PDF. */
export function buildReport(run: Run) {
  const parts = [
    `<h1>Sherpa checkout report</h1><p>${esc(run.store_url)} · ${new Date(run.created_at * 1000).toLocaleString()}</p>`,
  ];
  if (run.audit) parts.push(auditSection("Before", run.audit));
  if (run.fix) parts.push(`<h2>Pull request</h2><p><a href="${esc(run.fix.pr_url)}">${esc(run.fix.pr_url)}</a></p><p>${esc(run.fix.summary)}</p>`);
  if (run.verify) {
    parts.push(auditSection("After (preview)", run.verify.audit));
    if (run.verify.order) parts.push(`<p>Sandbox order ${esc(run.verify.order.id)}: ${esc(run.verify.order.status)}</p>`);
  }
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Sherpa report</title>
<style>body{font:15px/1.5 system-ui,sans-serif;max-width:760px;margin:40px auto;padding:0 16px;color:#16181d}
table{border-collapse:collapse}td{border-bottom:1px solid #ddd;padding:4px 16px 4px 0}li{margin:8px 0}</style>
</head><body>${parts.join("")}<p style="color:#777">PayPal sandbox only. Generated by Sherpa.</p></body></html>`;
}

export function downloadReport(run: Run) {
  const blob = new Blob([buildReport(run)], { type: "text/html" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = `sherpa-report-${run.id}.html`;
  a.click();
  URL.revokeObjectURL(a.href);
}
